<?php

namespace Fleetbase\FleetOps\Models;

use Fleetbase\Casts\Json;
use Fleetbase\Models\Model;
use Fleetbase\Traits\HasApiModelBehavior;
use Fleetbase\Traits\HasInternalId;
use Fleetbase\Traits\HasMetaAttributes;
use Fleetbase\Traits\HasPublicId;
use Fleetbase\Traits\HasUuid;
use Fleetbase\Traits\Searchable;
use Fleetbase\Traits\TracksApiCredential;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Manifest.
 *
 * Represents a committed delivery plan for a specific vehicle and (optionally)
 * driver. Generated by the Orchestrator commit step. Each Manifest contains an
 * ordered list of ManifestStops representing the physical locations to visit.
 *
 * Status lifecycle:
 *   draft → published → active → completed
 *                    ↘ cancelled (from any status before completed)
 *
 *   draft      generated by the Orchestrator; only dispatchers see it
 *   published  released to the driver (`published_at`); Navigator shows it
 *   active     the driver has started it (first stop arrived or done)
 *   completed  every stop is done
 *
 * `in_progress` is the status older builds wrote once a route started. It is
 * still read as started, so rows that carry it keep working.
 *
 * A publish can be booked for later with `publish_at`; the queued
 * PublishScheduledManifest job carries it out.
 */
class Manifest extends Model
{
    use HasUuid;
    use HasPublicId;
    use HasInternalId;
    use HasMetaAttributes;
    use HasApiModelBehavior;
    use TracksApiCredential;
    use Searchable;
    use SoftDeletes;

    /**
     * The database table used by the model.
     */
    protected $table = 'manifests';

    /**
     * The type of public ID to generate.
     */
    protected $publicIdType = 'manifest';

    public const STATUS_DRAFT       = 'draft';
    public const STATUS_PUBLISHED   = 'published';
    public const STATUS_ACTIVE      = 'active';
    public const STATUS_IN_PROGRESS = 'in_progress';
    public const STATUS_COMPLETED   = 'completed';
    public const STATUS_CANCELLED   = 'cancelled';

    /**
     * Statuses a driver may see: published or later. A draft is the
     * dispatcher's working copy and never reaches a driver.
     */
    public const DRIVER_VISIBLE_STATUSES = ['published', 'active', 'in_progress', 'completed'];

    /**
     * Statuses whose stops can still change: a stop can be added, moved or
     * re-sequenced on these. Completed and cancelled routes are history.
     */
    public const OPEN_STATUSES = ['draft', 'published', 'active', 'in_progress'];

    /**
     * Statuses of a route the driver has started.
     */
    public const STARTED_STATUSES = ['active', 'in_progress'];

    /**
     * Columns that can be searched.
     */
    protected $searchableColumns = ['public_id', 'internal_id'];

    /**
     * Mass-assignable attributes.
     */
    protected $fillable = [
        'company_uuid',
        'driver_uuid',
        'vehicle_uuid',
        'status',
        'scheduled_date',
        'published_at',
        'publish_at',
        'started_at',
        'completed_at',
        'total_distance_m',
        'total_duration_s',
        'stop_count',
        'notes',
        'meta',
    ];

    /**
     * Attribute casts.
     */
    protected $casts = [
        'meta'           => Json::class,
        'scheduled_date' => 'date',
        'published_at'   => 'datetime',
        'publish_at'     => 'datetime',
        'started_at'     => 'datetime',
        'completed_at'   => 'datetime',
    ];

    /**
     * Attributes appended to the model's JSON representation.
     */
    protected $appends = [
        'driver_name',
        'vehicle_name',
        'completed_stops',
        'pending_stops',
    ];

    // ── Relationships ─────────────────────────────────────────────────────────

    /**
     * The driver assigned to this manifest.
     */
    public function driver(): BelongsTo
    {
        return $this->belongsTo(Driver::class, 'driver_uuid', 'uuid');
    }

    /**
     * The vehicle assigned to this manifest.
     */
    public function vehicle(): BelongsTo
    {
        return $this->belongsTo(Vehicle::class, 'vehicle_uuid', 'uuid');
    }

    /**
     * The ordered list of stops in this manifest.
     */
    public function stops(): HasMany
    {
        return $this->hasMany(ManifestStop::class, 'manifest_uuid', 'uuid')
            ->orderBy('sequence');
    }

    /**
     * The orders associated with this manifest (through stops).
     */
    public function orders(): HasMany
    {
        return $this->hasMany(Order::class, 'manifest_uuid', 'uuid');
    }

    // ── Computed Attributes ───────────────────────────────────────────────────

    public function getDriverNameAttribute(): ?string
    {
        return $this->driver?->name;
    }

    public function getVehicleNameAttribute(): ?string
    {
        return $this->vehicle?->display_name;
    }

    public function getCompletedStopsAttribute(): int
    {
        return $this->stops()->where('status', 'completed')->count();
    }

    public function getPendingStopsAttribute(): int
    {
        return $this->stops()->whereIn('status', ['pending', 'arrived'])->count();
    }

    // ── Scopes ────────────────────────────────────────────────────────────────

    public function scopeForCompany($query, string $companyUuid)
    {
        return $query->where('company_uuid', $companyUuid);
    }

    public function scopeActive($query)
    {
        return $query->whereIn('status', self::STARTED_STATUSES);
    }

    /**
     * Manifests a driver may see: published or later, and a cancelled route
     * only when it had been published, so a driver hears that a route they
     * were given was called off but never sees a cancelled draft.
     */
    public function scopeVisibleToDriver($query)
    {
        return $query->where(function ($query) {
            $query->whereIn('status', self::DRIVER_VISIBLE_STATUSES)
                ->orWhere(function ($query) {
                    $query->where('status', self::STATUS_CANCELLED)->whereNotNull('published_at');
                });
        });
    }

    /**
     * Manifests whose stops can still change.
     */
    public function scopeOpen($query)
    {
        return $query->whereIn('status', self::OPEN_STATUSES);
    }

    public function scopeForDriver($query, string $driverUuid)
    {
        return $query->where('driver_uuid', $driverUuid);
    }

    public function scopeForVehicle($query, string $vehicleUuid)
    {
        return $query->where('vehicle_uuid', $vehicleUuid);
    }

    // ── Business Logic ────────────────────────────────────────────────────────

    public function isOpen(): bool
    {
        return in_array($this->status, self::OPEN_STATUSES, true);
    }

    public function isDraft(): bool
    {
        return $this->status === self::STATUS_DRAFT;
    }

    public function isVisibleToDriver(): bool
    {
        return in_array($this->status, self::DRIVER_VISIBLE_STATUSES, true)
            || ($this->status === self::STATUS_CANCELLED && $this->published_at !== null);
    }

    /**
     * Release a draft to its driver. Returns false, changing nothing, when the
     * manifest is not a draft: publishing is a one-way step and running it
     * twice must not move `published_at`.
     *
     * Side effects (telling the driver) belong to Support\Dispatch\ManifestPublisher.
     */
    public function markPublished(): bool
    {
        if (!$this->isDraft()) {
            return false;
        }

        $this->update(['status' => self::STATUS_PUBLISHED, 'published_at' => now(), 'publish_at' => null]);

        return true;
    }

    /**
     * Mark the manifest as started and record the start time.
     */
    public function start(): self
    {
        $this->update(['status' => self::STATUS_ACTIVE, 'started_at' => now()]);

        return $this;
    }

    /**
     * A published route becomes active the first time the driver works one of
     * its stops. Routes in any other status are left as they are.
     */
    public function activateIfPublished(): self
    {
        if ($this->status === self::STATUS_PUBLISHED) {
            $this->start();
        }

        return $this;
    }

    /**
     * Mark the manifest as completed and record the completion time.
     */
    public function complete(): self
    {
        $this->update(['status' => self::STATUS_COMPLETED, 'completed_at' => now()]);

        return $this;
    }

    /**
     * Cancel the manifest.
     */
    public function cancel(): self
    {
        $this->update(['status' => self::STATUS_CANCELLED, 'publish_at' => null]);

        return $this;
    }

    /**
     * Check whether all stops are completed and auto-complete the manifest.
     */
    public function checkAndAutoComplete(): void
    {
        $pendingCount = $this->stops()->whereIn('status', ['pending', 'arrived'])->count();
        if ($pendingCount === 0 && in_array($this->status, self::STARTED_STATUSES, true)) {
            $this->complete();
        }
    }
}
